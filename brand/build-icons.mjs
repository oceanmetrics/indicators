/** read icon-paths.ts through Node's type stripping: it holds only literals, so the import is deterministic */
export async function loadIconPaths() {
  const m = await import(pathToFileURL(PATHS_FILE).href);
  return { paths: { ...m.ICON_PATHS }, sources: { ...m.ICON_SOURCES } };
}

async function main() {
  const { paths, sources } = await loadIconPaths();
  const lock = existsSync(LOCK_FILE) ? JSON.parse(readFileSync(LOCK_FILE, "utf8")) : {};
  const problems = checkLock(paths, lock);
  if (problems.length) {
    process.stderr.write(`build-icons: ${problems.join("; ")} (icons.lock.json; v1 glyphs never change)\n`);
    process.exit(1);
  }
  mkdirSync(OUT_DIR, { recursive: true });
  const sprite = generateSprite(paths);
  const css = generateCss(paths);
  writeFileSync(SPRITE_FILE, sprite);
  writeFileSync(CSS_FILE, css);
  writeFileSync(SHEET_FILE, generateSheet(paths, sources, readFileSync(THEME_FILE, "utf8")));
  if (process.argv.includes("--lock")) {
    writeFileSync(LOCK_FILE, JSON.stringify({ ...generateLock(paths) }, null, 2) + "\n");
    process.stdout.write(`build-icons: wrote ${LOCK_FILE}\n`);
  }
  process.stdout.write(
    `build-icons: ${Object.keys(paths).length} glyphs; sprite ${(sprite.length / 1e3).toFixed(1)} KB, icons.css ${(css.length / 1e3).toFixed(1)} KB\n`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    process.stderr.write(`build-icons: ${e.message}\n`);
    process.exit(1);
  });
}
