// generates src/icons/icon-paths.ts, the ONE name -> path map of the Ocean Metrics icon set (written as the viewer's two
// parts, icon-core.ts and icon-paths-eov.ts, which icon-paths.ts composes), from three sources:
//   1. MDI: brand/icon-map.json (name -> @mdi/js export), imported BY EXPORT NAME; a missing export is an error
//   2. bespoke glyphs: brand/glyphs/bespoke.json, drawn by brand/glyphs.py from primitives
//   3. EOV glyphs: brand/glyphs/eov.json (traced from the GOOS badges by brand/eov_trace.py) plus eov.meta.json;
//      a glyph that does not read at 16 px (readable_16 false) is replaced by its MDI fallback export.
//      both files are optional until the trace exists.
// no path is ever typed by hand. every function here is PURE (the sources are passed in); importing this module
// writes nothing; only main() touches the filesystem, and only when the script is run directly.
//   node brand/build-icon-paths.mjs            (npm run icons:paths)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const ICON_MAP_FILE = resolve(ROOT, "brand/icon-map.json");
export const BESPOKE_FILE = resolve(ROOT, "brand/glyphs/bespoke.json");
export const EOV_FILE = resolve(ROOT, "brand/glyphs/eov.json");
export const EOV_META_FILE = resolve(ROOT, "brand/glyphs/eov.meta.json");
export const OUTPUT_FILE = resolve(ROOT, "src/icons/icon-paths.ts");
// the viewer's split of the same map: every family but eov- up front, the eov- paths (traced: most of the set's weight) on first use
export const CORE_FILE = resolve(ROOT, "src/icons/icon-core.ts");
export const EOV_PATHS_FILE = resolve(ROOT, "src/icons/icon-paths-eov.ts");

/** the family of a name is its prefix up to the first "-" (ui-search -> ui) */
export const familyOf = (name) => name.slice(0, name.indexOf("-"));

/**
 * Resolve every source into { paths, sources }.
 * @param {Record<string,string>} iconMap name -> @mdi/js export name
 * @param {Record<string,string>} mdiModule the imported `@mdi/js` module (a fake object in tests)
 * @param {Record<string,string>} bespoke name -> path data (glyphs.py)
 * @param {Record<string,string>} eov name -> path data (eov_trace.py); may be empty
 * @param {Record<string,any>} eovMeta name -> {readable_16, fallback}; may be empty
 * @returns {{paths: Record<string,string>, sources: Record<string,string>}}
 */
export function resolveIconPaths(iconMap, mdiModule, bespoke = {}, eov = {}, eovMeta = {}) {
  const paths = {};
  const sources = {};
  const add = (name, d, source) => {
    if (name in paths) {
      throw new Error(`icon name "${name}" is defined twice (${sources[name]} and ${source})`);
    }
    paths[name] = d;
    sources[name] = source;
  };
  const mdi = (exportName, name) => {
    if (!(exportName in mdiModule) || typeof mdiModule[exportName] !== "string") {
      throw new Error(`@mdi/js has no export named "${exportName}" (icon "${name}")`);
    }
    return mdiModule[exportName];
  };
  for (const [name, exportName] of Object.entries(iconMap)) {
    add(name, mdi(exportName, name), `mdi:${exportName}`);
  }
  for (const [name, d] of Object.entries(bespoke)) add(name, d, "glyph");
  // eov: the trace, or the MDI fallback where the trace is not readable at 16 px
  const meta = eovMeta.entries ?? eovMeta;
  for (const name of [...new Set([...Object.keys(eov), ...Object.keys(meta)])].sort()) {
    const m = meta[name] ?? {};
    if (m.readable_16 === false) {
      const fb = m.fallback ?? m.mdi_fallback ?? m.fallback_mdi;
      if (!fb) throw new Error(`eov glyph "${name}" is not readable at 16 px and names no MDI fallback`);
      add(name, mdi(fb, name), `mdi-fallback:${fb}`);
    } else {
      if (!(name in eov)) throw new Error(`eov glyph "${name}" has metadata but no traced path`);
      add(name, eov[name], "eov-trace");
    }
  }
  const byPath = new Map();
  for (const [name, d] of Object.entries(paths)) {
    byPath.set(d, [...(byPath.get(d) ?? []), name]);
  }
  const dups = [...byPath.values()].filter((names) => names.length > 1);
  if (dups.length) throw new Error(`duplicate path shared by ${dups.map((names) => names.join(" = ")).join("; ")}`);
  for (const name of Object.keys(paths)) {
    if (!/^[a-z]+-[a-z0-9-]+$/.test(name)) throw new Error(`icon name "${name}" is not <family>-<name>`);
  }
  return { paths, sources };
}

const HEADER = (what) => `/**
 * GENERATED by brand/build-icon-paths.mjs (npm run icons:paths). Do not edit by hand.
 * Sources: @mdi/js by export name (brand/icon-map.json), brand/glyphs/bespoke.json (drawn by brand/glyphs.py),
 * brand/glyphs/eov.json (traced from the GOOS EOV icons, adapted: Martin Miguez et al. 2026, Front. Mar. Sci., CC BY).
 * brand/icons.test.ts proves every MDI path equals its export and that regenerating this file is byte-identical.
 * ${what}
 */
`;
const isEov = (n) => familyOf(n) === "eov";

/**
 * PURE: the text of src/icons/icon-paths.ts, the whole name -> path map (the sprite, icons.css, the contact sheet and the
 * tests read it), composed from the viewer's two parts so each path is written once
 */
export function generateIconPathsSource(paths, sources) {
  const names = Object.keys(paths).sort();
  const families = {};
  for (const n of names) (families[familyOf(n)] ??= []).push(n);
  const q = JSON.stringify;
  return `${HEADER("The whole set: icon-core.ts (loaded up front by the viewer) and icon-paths-eov.ts (loaded on first use).")}
import { CORE_PATHS } from "./icon-core.ts";
import { EOV_PATHS } from "./icon-paths-eov.ts";

/** every name -> its path, in name order */
export const ICON_PATHS = Object.fromEntries(
  Object.entries({ ...CORE_PATHS, ...EOV_PATHS }).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
) as typeof CORE_PATHS & typeof EOV_PATHS;

export type IconName = keyof typeof CORE_PATHS | keyof typeof EOV_PATHS;

/** where each path comes from: 'mdi:<export>', 'glyph', 'eov-trace' or 'mdi-fallback:<export>' */
export const ICON_SOURCES: Record<IconName, string> = {
${names.map((n) => `  ${q(n)}: ${q(sources[n])},`).join("\n")}
};

/** family prefix -> its names */
export const ICON_FAMILIES = {
${Object.keys(families).sort().map((f) => `  ${q(f)}: [${families[f].map(q).join(", ")}],`).join("\n")}
} as const;
`;
}

/** PURE: the text of src/icons/icon-core.ts: every path but the eov- family, and the eov- names */
export function generateIconCoreSource(paths) {
  const names = Object.keys(paths).sort();
  const q = JSON.stringify;
  return `${HEADER("The viewer's up-front part: every family but eov-, whose paths load on first use (icon-paths-eov.ts).")}
export const CORE_PATHS = {
${names.filter((n) => !isEov(n)).map((n) => `  ${q(n)}: ${q(paths[n])},`).join("\n")}
} as const;

/** the eov- names, so a name can be checked without loading their paths */
export const EOV_NAMES: readonly string[] = [
${names.filter(isEov).map((n) => `  ${q(n)},`).join("\n")}
];
`;
}

/** PURE: the text of src/icons/icon-paths-eov.ts: the eov- paths, a chunk of its own in the viewer */
export function generateEovPathsSource(paths) {
  const names = Object.keys(paths).sort().filter(isEov);
  const q = JSON.stringify;
  return `${HEADER("The eov- paths: the viewer loads this chunk the first time an eov- glyph is drawn (src/icons/eov.svelte.ts).")}
export const EOV_PATHS = {
${names.map((n) => `  ${q(n)}: ${q(paths[n])},`).join("\n")}
} as const;
`;
}

const readJson = (file, fallback) => (existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : fallback);

/** read every source file from disk and resolve it (the one place that touches the filesystem) */
export async function loadAndResolve() {
  const mdiModule = await import("@mdi/js");
  return resolveIconPaths(
    readJson(ICON_MAP_FILE, {}),
    mdiModule,
    readJson(BESPOKE_FILE, {}),
    readJson(EOV_FILE, {}),
    readJson(EOV_META_FILE, {}),
  );
}

async function main() {
  const { paths, sources } = await loadAndResolve();
  writeFileSync(CORE_FILE, generateIconCoreSource(paths));
  writeFileSync(EOV_PATHS_FILE, generateEovPathsSource(paths));
  writeFileSync(OUTPUT_FILE, generateIconPathsSource(paths, sources));
  process.stdout.write(`build-icon-paths: wrote ${OUTPUT_FILE}, ${CORE_FILE} and ${EOV_PATHS_FILE} (${Object.keys(paths).length} icons)\n`);
}

// run only when executed directly, never on import
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    process.stderr.write(`build-icon-paths: ${e.message}\n`);
    process.exit(1);
  });
}
